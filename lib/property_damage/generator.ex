defmodule PropertyDamage.Generator do
  @moduledoc """
  Generates command sequences for stateful property-based testing.

  This module produces `PropertyDamage.Sequence` structs whose commands run
  one after another:

      Generator.generate_sequence(MyModel, max_commands: 20)
      # => StreamData producing %Sequence{prefix: [...]}

  ## Placeholders

  A value the system mints is a placeholder (see `PropertyDamage.External`).
  The generator simulates each command it draws, so a later command can use a
  placeholder an earlier command minted.

  ## Setup and teardown commands

  A model's setup commands (`c:PropertyDamage.Model.setup_each/0`) are generated
  first, inside the same draw as the roots: every entry in written order, with
  no `when:` filter and no weighted pick, each simulated at its
  `Position.setup/1` position. The roots are then generated from the state the
  setup commands left. A model without setup commands adds nothing to the
  draw, so its seeds draw what they always drew.

  Teardown commands depend on the roots, and a shrink attempt redraws them for
  each candidate, so they are generated by `teardown_commands/4` from the run seed
  after the roots.

  ## Auto-Lifting

  Raw values passed as overrides are automatically wrapped in `StreamData.constant/1`:

      merge_overrides(base, %{currency: "USD"})
      merge_overrides(base, %{currency: StreamData.member_of(["USD", "EUR"])})
  """

  alias PropertyDamage.External
  alias PropertyDamage.Mint
  alias PropertyDamage.{Placeholder, PlaceholderRegistry, Sequence}
  alias PropertyDamage.Sequence.Position

  @type command :: struct()
  @type state :: map()
  @type weighted_command :: {pos_integer(), module()}

  # Default options
  @default_max_commands 50

  # ============================================================================
  # Public API
  # ============================================================================

  @doc """
  Generate a command sequence for a given model.

  ## Parameters

  - `model` - Model module defining commands and state projection
  - `opts` - Options:
    - `:max_commands` - Maximum total commands per sequence (default: 50)
    - `:external_markers` - Atom markers that stand for a minted value (see
      `PropertyDamage.External`; default `[]`)

  Note: the returned generator is pure; reproducibility comes from consuming
  it with `generate_value/3` and an explicit seed.

  ## Returns

  A StreamData generator that produces `PropertyDamage.Sequence` structs.

  ## Examples

      Generator.generate_sequence(MyModel, max_commands: 20)
  """
  @spec generate_sequence(module(), keyword()) :: StreamData.t(PropertyDamage.Sequence.t())
  def generate_sequence(model, opts \\ []) do
    max_commands = Keyword.get(opts, :max_commands, @default_max_commands)
    markers = Keyword.get(opts, :external_markers, [])
    commands = model.commands() |> PropertyDamage.Model.normalize_commands()
    projection = model.command_sequence_projection()
    setup = PropertyDamage.Model.setup_commands(model)

    StreamData.bind(StreamData.constant(nil), fn _ ->
      roots = fn initial_state ->
        do_generate_linear_sequence(
          commands,
          projection,
          model,
          initial_state,
          max_commands,
          markers
        )
      end

      case setup do
        # No setup commands: no extra draw, so every seed keeps its sequence.
        [] ->
          roots.(projection.init())

        _ ->
          setup
          |> generate_setup(projection, model, projection.init(), [], [], markers)
          |> StreamData.bind(fn {setup_commands, setup_ph, state} ->
            roots.(state)
            |> StreamData.map(&with_setup(&1, setup_commands, setup_ph))
          end)
      end
    end)
  end

  @doc """
  Draw the model's teardown commands for `sequence` and return the sequence
  carrying them.

  The setup commands and the roots are simulated again from the projection's
  initial state, as the generator reached them, and each teardown entry is
  generated in written order with its `overrides:` against that end state. The draw
  is seeded by `:erlang.phash2({run_seed, :teardown})`, so it is a pure
  function of the model, the sequence and the run seed, and it never changes
  the roots a seed draws. Placeholders the teardown commands' simulated events
  introduce are minted at `Position.teardown/1` positions and registered in the
  sequence's registry.

  Options: `:external_markers`, as for `generate_sequence/2`.
  """
  @spec teardown_commands(module(), Sequence.t(), integer(), keyword()) :: Sequence.t()
  def teardown_commands(model, %Sequence{} = sequence, run_seed, opts \\ []) do
    case PropertyDamage.Model.teardown_commands(model) do
      [] ->
        %{sequence | teardown: []}

      entries ->
        markers = Keyword.get(opts, :external_markers, [])
        projection = model.command_sequence_projection()
        state = end_state(model, projection, sequence, markers)

        {teardown, minted} =
          entries
          |> generate_teardown(projection, model, state, [], [], markers)
          |> generate_value(:erlang.phash2({run_seed, :teardown}))

        %{sequence | teardown: teardown, registry: register_all(sequence.registry, minted)}
    end
  end

  # Size passed to StreamData when realizing a value. Constant (rather than
  # growing per run) so that a sequence is a pure function of the seed alone,
  # which is what makes "reproduce with seed N" exact.
  @generation_size 30

  @doc """
  Deterministically realizes a single value from a StreamData generator.

  Consuming a generator via `Enum`/`Enumerable` seeds from the wall clock
  (see `StreamData` docs), which silently breaks seed reproducibility.
  All framework code MUST realize generated values through this function.

  Generation being a pure function of the seed also depends on user code
  (generators, `when:`/`overrides:`, the projection/simulator) being pure; enforce
  that with `PropertyDamage.audit/2` (`mix pd.audit`). See the
  [deterministic generation guide](deterministic_generation.md).
  """
  @spec generate_value(StreamData.t(val), integer(), keyword()) :: val when val: var
  def generate_value(generator, seed, opts \\ []) when is_integer(seed) do
    size = Keyword.get(opts, :size, @generation_size)

    generator
    |> StreamData.seeded(seed)
    |> StreamData.resize(size)
    |> Enum.at(0)
  end

  @doc """
  Derives the effective seed for a given run number from the base seed.

  Run 0 uses the base seed unchanged, so re-running a failure's reported
  seed with `max_runs: 1` regenerates exactly the failing sequence.
  Later runs get independent, well-mixed sub-seeds.
  """
  @spec run_seed(integer(), non_neg_integer()) :: integer()
  def run_seed(seed, 0) when is_integer(seed), do: seed

  def run_seed(seed, run_number) when is_integer(seed) and is_integer(run_number) do
    :erlang.phash2({seed, run_number}, 4_294_967_296)
  end

  @doc """
  Merge overrides into base generators, auto-lifting raw values.

  Raw values are automatically wrapped in `StreamData.constant/1`.
  StreamData generators are passed through unchanged.

  ## Parameters

  - `base` - Map of field names to StreamData generators
  - `overrides` - Map of field names to values or generators to override

  ## Returns

  A list of `{field, generator}` pairs sorted by field (a keyword list when
  the fields are atoms), for passing to `StreamData.fixed_map/1`. It is
  sorted because a map's iteration order depends on the VM, so drawing fields
  in map order would give one seed different field values in another VM.

  ## Examples

      iex> base = %{currency: StreamData.constant("USD"), amount: StreamData.positive_integer()}
      iex> result = PropertyDamage.Generator.merge_overrides(base, %{currency: "EUR"})
      iex> Keyword.keys(result)
      [:amount, :currency]
  """
  @spec merge_overrides(map(), map()) :: [{term(), StreamData.t(term())}]
  def merge_overrides(base, overrides) do
    base
    |> Map.merge(lift_values(overrides))
    |> Enum.sort_by(fn {field, _generator} -> field end)
  end

  @doc """
  Check if a value is a StreamData generator.

  ## Examples

      iex> PropertyDamage.Generator.stream_data?(StreamData.integer())
      true

      iex> PropertyDamage.Generator.stream_data?(42)
      false
  """
  @spec stream_data?(any()) :: boolean()
  def stream_data?(%StreamData{}), do: true
  def stream_data?(_), do: false

  # ============================================================================
  # Linear Sequence Generation
  # ============================================================================

  defp do_generate_linear_sequence(
         commands,
         projection,
         model,
         initial_state,
         max_commands,
         markers
       ) do
    generate_linear_recursive(
      commands,
      projection,
      model,
      initial_state,
      max_commands,
      [],
      [],
      markers,
      &Position.prefix/1
    )
    |> StreamData.map(fn {cmds, placeholders} ->
      attach_registry(Sequence.linear(cmds), placeholders)
    end)
  end

  # Recursion threads two accumulators: `acc` (commands, reversed) and `acc_ph`
  # (placeholders minted so far). `pos_fun` maps a command's local 0-based index
  # to its structured position (DR-021).
  defp generate_linear_recursive(_commands, _projection, _model, _state, 0, acc, acc_ph, _m, _pf) do
    StreamData.constant({Enum.reverse(acc), acc_ph})
  end

  defp generate_linear_recursive(
         commands,
         projection,
         model,
         state,
         remaining,
         acc,
         acc_ph,
         markers,
         pos_fun
       ) do
    valid_commands = filter_valid_commands(commands, state)

    case valid_commands do
      [] ->
        StreamData.constant({Enum.reverse(acc), acc_ph})

      _ ->
        StreamData.bind(weighted_member_of(valid_commands), fn {_weight, cmd_module, opts} ->
          generator = get_command_generator(cmd_module, opts, state)

          StreamData.bind(generator, fn command ->
            position = pos_fun.(length(acc))
            command = reify_command_mints(command, position)
            events = simulate_command(model, state, command)
            {events, minted} = instantiate_placeholders(events, position, markers)
            new_state = update_state(state, command, events, projection)
            new_acc = [command | acc]
            new_acc_ph = acc_ph ++ minted

            if terminate_early?(model, new_state, command, events) do
              StreamData.constant({Enum.reverse(new_acc), new_acc_ph})
            else
              generate_linear_recursive(
                commands,
                projection,
                model,
                new_state,
                remaining - 1,
                new_acc,
                new_acc_ph,
                markers,
                pos_fun
              )
            end
          end)
        end)
    end
  end

  # ============================================================================
  # Setup and Teardown Commands
  # ============================================================================

  # Draws every entry in written order: no `when:` filter, no weighted pick and
  # no terminate_early?/3. Each one is simulated at its setup position so the
  # next entry's `overrides:` (and the roots after them) see its state.
  defp generate_setup([], _projection, _model, state, acc, acc_ph, _markers),
    do: StreamData.constant({Enum.reverse(acc), acc_ph, state})

  defp generate_setup([entry | rest], projection, model, state, acc, acc_ph, markers) do
    {_weight, module, spec} = entry

    StreamData.bind(get_command_generator(module, spec, state), fn command ->
      position = Position.setup(length(acc))
      {command, state, minted} = simulate_at(command, position, state, projection, model, markers)
      generate_setup(rest, projection, model, state, [command | acc], acc_ph ++ minted, markers)
    end)
  end

  defp generate_teardown([], _projection, _model, _state, acc, acc_ph, _markers),
    do: StreamData.constant({Enum.reverse(acc), acc_ph})

  defp generate_teardown([entry | rest], projection, model, state, acc, acc_ph, markers) do
    {_weight, module, spec} = entry

    StreamData.bind(get_command_generator(module, spec, state), fn command ->
      position = Position.teardown(length(acc))
      {command, state, minted} = simulate_at(command, position, state, projection, model, markers)

      generate_teardown(
        rest,
        projection,
        model,
        state,
        [command | acc],
        acc_ph ++ minted,
        markers
      )
    end)
  end

  # One generation step for a command already generated: reify its mint markers,
  # simulate it, mint its placeholders at `position` and fold it.
  defp simulate_at(command, position, state, projection, model, markers) do
    command = reify_command_mints(command, position)
    events = simulate_command(model, state, command)
    {events, minted} = instantiate_placeholders(events, position, markers)
    {command, update_state(state, command, events, projection), minted}
  end

  # The generated root sequence with the setup commands in front: the setup
  # placeholders join the sequence's registry.
  defp with_setup(sequence, setup_commands, setup_ph) do
    %{sequence | setup: setup_commands, registry: register_all(sequence.registry, setup_ph)}
  end

  defp register_all(registry, []), do: registry
  defp register_all(nil, placeholders), do: build_registry(placeholders)

  defp register_all(registry, placeholders),
    do: Enum.reduce(placeholders, registry, &PlaceholderRegistry.register(&2, &1))

  # The state the generator reached at the end of `sequence`: the setup
  # commands and the roots simulated again from the initial state.
  #
  # Each placeholder a simulated event introduces is the one the sequence's
  # registry links to the command's position, so a teardown command generated
  # against this state consumes ids the run resolves. The two differ when the
  # sequence is a shrink candidate: its commands moved to new positions, and
  # its registry links each new position to the placeholders generation
  # minted at the command's original one. The commands keep the mint markers
  # generation reified for them.
  defp end_state(model, projection, %Sequence{} = sequence, markers) do
    step = fn command, position, state ->
      events = simulate_command(model, state, command)
      {events, _minted} = instantiate_placeholders(events, position, markers)
      events = relink(events, position, sequence.registry)
      update_state(state, command, events, projection)
    end

    fold = fn commands, pos_fun, state ->
      commands
      |> Enum.with_index()
      |> Enum.reduce(state, fn {command, i}, acc -> step.(command, pos_fun.(i), acc) end)
    end

    state = fold.(sequence.setup, &Position.setup/1, projection.init())
    fold.(sequence.prefix, &Position.prefix/1, state)
  end

  # The registry's placeholders for the command at `position`, in place of
  # the ones simulating it there minted, matched by event index and path.
  defp relink(events, _position, nil), do: events

  defp relink(events, position, registry) do
    linked =
      registry
      |> PlaceholderRegistry.ids_at_position(position)
      |> Map.new(fn {_position, event_index, path} = id ->
        {{event_index, path}, PlaceholderRegistry.get(registry, id)}
      end)

    if map_size(linked) == 0, do: events, else: relink_value(events, linked)
  end

  defp relink_value(%Placeholder{} = placeholder, linked) do
    {_position, event_index, path} = Placeholder.id(placeholder)
    Map.get(linked, {event_index, path}) || placeholder
  end

  defp relink_value(%module{} = struct, linked) do
    struct
    |> Map.from_struct()
    |> Map.new(fn {key, value} -> {key, relink_value(value, linked)} end)
    |> then(&struct(module, &1))
  end

  defp relink_value(map, linked) when is_map(map),
    do: Map.new(map, fn {key, value} -> {key, relink_value(value, linked)} end)

  defp relink_value(list, linked) when is_list(list),
    do: Enum.map(list, &relink_value(&1, linked))

  defp relink_value(value, _linked), do: value

  # ============================================================================
  # Steps for expansions
  # ============================================================================

  @doc false
  # The simulated state after the setup commands of `sequence`, from the
  # projection's initial state: where a variant's walk over the roots starts.
  @spec setup_state(module(), Sequence.t(), keyword()) :: map()
  def setup_state(model, %Sequence{} = sequence, opts \\ []) do
    markers = Keyword.get(opts, :external_markers, [])
    projection = model.command_sequence_projection()

    sequence.setup
    |> Enum.with_index()
    |> Enum.reduce(projection.init(), fn {command, offset}, state ->
      simulate_linked(
        model,
        projection,
        command,
        Position.setup(offset),
        state,
        sequence.registry,
        markers
      )
    end)
  end

  @doc false
  # Simulates a root at `position` from `state` and folds it. The placeholders
  # its events carry are the ones `registry` links to that position, so a walk
  # over a shrink candidate folds the ids generation minted. Options:
  # `:external_markers`, as for `generate_sequence/2`.
  @spec simulate_root(
          module(),
          struct(),
          Position.t(),
          map(),
          PlaceholderRegistry.t() | nil,
          keyword()
        ) :: map()
  def simulate_root(model, command, position, state, registry, opts \\ []) do
    markers = Keyword.get(opts, :external_markers, [])
    projection = model.command_sequence_projection()
    simulate_linked(model, projection, command, position, state, registry, markers)
  end

  defp simulate_linked(model, projection, command, position, state, registry, markers) do
    events = simulate_command(model, state, command)
    {events, _minted} = instantiate_placeholders(events, position, markers)
    events = relink(events, position, registry)
    update_state(state, command, events, projection)
  end

  @doc false
  # One generation step for a command generated outside the root pick (a leaf of
  # an expansion): reifies its mint markers at `position`, simulates it, mints
  # its placeholders at `position` and folds it. Returns
  # `{command, events, state, minted}`.
  @spec simulate_step(module(), struct(), Position.t(), map(), keyword()) ::
          {struct(), [struct()], map(), [Placeholder.t()]}
  def simulate_step(model, command, position, state, opts \\ []) do
    markers = Keyword.get(opts, :external_markers, [])
    projection = model.command_sequence_projection()
    command = reify_command_mints(command, position)
    events = simulate_command(model, state, command)
    {events, minted} = instantiate_placeholders(events, position, markers)
    {command, events, update_state(state, command, events, projection), minted}
  end

  @doc false
  # Folds `command` and the `events` simulated for it into `state`, as a step
  # folds them, without simulating the command again.
  @spec fold_step(module(), struct(), [struct()], map()) :: map()
  def fold_step(model, command, events, state) do
    update_state(state, command, events, model.command_sequence_projection())
  end

  @doc false
  # The generator of `module`'s commands with `overrides` (a map) applied, as
  # the root draw builds it: through `generator/1`, with every override key
  # checked against the command's fields.
  @spec command_generator(module(), map(), map()) :: StreamData.t(struct())
  def command_generator(module, overrides, state) do
    get_command_generator(module, %{overrides: overrides}, state)
  end

  @doc false
  # Whether `spec`'s `when:` holds in `state` (a spec without one always holds).
  @spec precondition_holds?(map(), map()) :: boolean()
  def precondition_holds?(spec, state), do: when_satisfied?(spec, state)

  # ============================================================================
  # Shared Helpers
  # ============================================================================

  defp filter_valid_commands(commands, state) do
    Enum.filter(commands, fn {_weight, _cmd_module, spec} ->
      when_satisfied?(spec, state)
    end)
  end

  defp when_satisfied?(spec, state) do
    # spec is now a map with :when key
    case Map.get(spec, :when) do
      nil -> true
      pred when is_function(pred, 1) -> pred.(state)
    end
  end

  defp weighted_member_of(weighted_commands) do
    total_weight = Enum.reduce(weighted_commands, 0, fn {w, _, _}, acc -> acc + w end)

    StreamData.bind(StreamData.integer(1..total_weight), fn n ->
      select_by_weight(weighted_commands, n)
      |> StreamData.constant()
    end)
  end

  defp select_by_weight([{weight, cmd, opts} | rest], n) do
    if n <= weight do
      {weight, cmd, opts}
    else
      select_by_weight(rest, n - weight)
    end
  end

  defp get_command_generator(cmd_module, spec, state) do
    # spec is now a map with :overrides key
    overrides =
      case Map.get(spec, :overrides) do
        nil -> %{}
        fun when is_function(fun, 1) -> fun.(state)
        map when is_map(map) -> map
      end

    validate_override_keys!(cmd_module, overrides)

    cmd_module.generator(overrides)
    |> StreamData.map(&struct!(cmd_module, &1))
  end

  # An `overrides:` option only takes effect for fields the command defines (the
  # generated map is built into the command struct, which rejects unknown keys).
  # An override targeting any other key is a silent no-op; surface it with a clear
  # error naming the command and offending field(s) rather than the opaque
  # KeyError that `struct!/2` would otherwise raise deep inside generation.
  defp validate_override_keys!(cmd_module, overrides) when map_size(overrides) > 0 do
    if Code.ensure_loaded?(cmd_module) and function_exported?(cmd_module, :__struct__, 0) do
      fields = cmd_module.__struct__() |> Map.from_struct() |> Map.keys()
      unknown = Map.keys(overrides) -- fields

      if unknown != [] do
        raise ArgumentError,
              "Invalid `overrides:` for command #{inspect(cmd_module)}: " <>
                "field(s) #{inspect(unknown)} are not defined by the command " <>
                "(its fields are #{inspect(fields)}). An override for an undefined " <>
                "field has no effect; check for a typo or a renamed field."
      end
    end

    :ok
  end

  defp validate_override_keys!(_cmd_module, _overrides), do: :ok

  defp simulate_command(model, state, command) do
    # Ensure the module is loaded before function_exported?/3, which is false
    # for a not-yet-loaded module.
    if Code.ensure_loaded?(model) and function_exported?(model, :simulator, 0) do
      model.simulator().simulate(command, state)
    else
      []
    end
  end

  defp update_state(state, command, events, projection) do
    state
    |> projection.apply(command)
    |> apply_events(events, projection)
  end

  defp apply_events(state, events, projection) do
    Enum.reduce(events, state, fn event, acc ->
      projection.apply(acc, event)
    end)
  end

  defp terminate_early?(model, state, command, events) do
    if Code.ensure_loaded?(model) and function_exported?(model, :terminate_early?, 3) do
      model.terminate_early?(state, command, events)
    else
      false
    end
  end

  defp lift_values(map) do
    Map.new(map, fn {k, v} -> {k, lift(v)} end)
  end

  defp lift(%StreamData{} = gen), do: gen
  defp lift(value), do: StreamData.constant(value)

  # ============================================================================
  # Placeholder instantiation (DR-021)
  # ============================================================================

  # Replace external() markers in simulated events with %Placeholder{} structs,
  # so projection state (and any consumer command that reads it) carries a
  # resolvable placeholder rather than a raw %External{} sentinel. Returns the
  # substituted events plus the list of minted placeholders for this command.
  defp instantiate_placeholders(events, position, markers) when is_list(events) do
    events
    |> Enum.with_index()
    |> Enum.map_reduce([], fn {event, event_index}, minted ->
      mint_event_placeholders(event, event_index, position, markers, minted)
    end)
  end

  defp instantiate_placeholders(events, _position, _markers), do: {events, []}

  # Reify any mint_per_run markers in a generated command with their generation
  # coordinates (DR-034/DR-036): the command's structured `position` and the
  # field path. Baking coordinates in here (rather than keying on the flat
  # executor index) makes the minted value
  # stable under shrinking, since the marker travels inside the command struct.
  defp reify_command_mints(command, position) when is_struct(command) do
    reify_mints(command, position, [])
  end

  defp reify_command_mints(command, _position), do: command

  defp reify_mints(%Mint{} = marker, position, path), do: Mint.reify(marker, position, path)
  defp reify_mints(%Placeholder{} = p, _position, _path), do: p

  defp reify_mints(%{__struct__: mod} = struct, position, path) do
    struct
    |> Map.from_struct()
    |> Map.new(fn {k, v} -> {k, reify_mints(v, position, path ++ [k])} end)
    |> then(&struct(mod, &1))
  end

  defp reify_mints(map, position, path) when is_map(map) do
    Map.new(map, fn {k, v} -> {k, reify_mints(v, position, path ++ [k])} end)
  end

  defp reify_mints(list, position, path) when is_list(list) do
    list
    |> Enum.with_index()
    |> Enum.map(fn {v, i} -> reify_mints(v, position, path ++ [i]) end)
  end

  defp reify_mints(tuple, position, path) when is_tuple(tuple) do
    tuple
    |> Tuple.to_list()
    |> Enum.with_index()
    |> Enum.map(fn {v, i} -> reify_mints(v, position, path ++ [i]) end)
    |> List.to_tuple()
  end

  defp reify_mints(other, _position, _path), do: other

  defp mint_event_placeholders(event, event_index, position, markers, minted)
       when is_struct(event) do
    paths = External.external_paths(event.__struct__, markers)

    Enum.reduce(paths, {event, minted}, fn path, {ev, ms} ->
      ph = Placeholder.new_at(ev.__struct__, path, position, event_index)
      {External.put_at_path(ev, path, ph), ms ++ [ph]}
    end)
  end

  defp mint_event_placeholders(event, _event_index, _position, _markers, minted) do
    {event, minted}
  end

  defp attach_registry(sequence, []), do: sequence

  defp attach_registry(sequence, placeholders) do
    Sequence.with_registry(sequence, build_registry(placeholders))
  end

  defp build_registry(placeholders) do
    Enum.reduce(placeholders, PlaceholderRegistry.new(), &PlaceholderRegistry.register(&2, &1))
  end

  # ============================================================================
  # Consumer-routing affordance (DR-021)
  # ============================================================================

  @doc """
  List the external placeholders available in projection `state`.

  During generation, `external()` markers in simulated events become
  `%PropertyDamage.Placeholder{}` structs embedded in projection state. This
  surfaces them so a model's `overrides:` function can route one into a command that
  consumes a server-generated value.

  ## Options

  - `:event_module` - keep only placeholders produced by this event module
  - `:path` - keep only placeholders at this field path (e.g. `[:id]`)

  ## Example

      # In the model's command list:
      {ViewOrder, overrides: fn state ->
        %{order_id: PropertyDamage.Generator.external_from(state, path: [:id])}
      end}
  """
  @spec available_externals(map(), keyword()) :: [struct()]
  def available_externals(state, opts \\ []) do
    state
    |> PlaceholderRegistry.collect_placeholders()
    |> filter_by(
      :event_module,
      Keyword.get(opts, :event_module),
      &(Placeholder.event_module(&1) == &2)
    )
    |> filter_by(:path, Keyword.get(opts, :path), &(Placeholder.path(&1) == &2))
  end

  @doc """
  A seeded generator that picks one external placeholder from `state`.

  Returns `StreamData.constant(nil)` when no matching external is available, so
  an `overrides:` function can guard on `nil`. Accepts the same options as
  `available_externals/2`.
  """
  @spec external_from(map(), keyword()) :: StreamData.t(struct() | nil)
  def external_from(state, opts \\ []) do
    case available_externals(state, opts) do
      [] -> StreamData.constant(nil)
      placeholders -> StreamData.member_of(placeholders)
    end
  end

  defp filter_by(list, _key, nil, _pred), do: list
  defp filter_by(list, _key, value, pred), do: Enum.filter(list, &pred.(&1, value))
end
