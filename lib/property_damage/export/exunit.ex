defmodule PropertyDamage.Export.ExUnit do
  @moduledoc false

  alias PropertyDamage.Export.Common
  alias PropertyDamage.FailureReport

  @doc """
  Generates an ExUnit test module from a failure report.

  The generated test takes one of two forms. The regression guard (the
  default, `expect_fixed: true`) fails if the run finds any failure, so it
  fails while the bug is present and again if the bug comes back. The
  reproduce form (`expect_fixed: false`) fails if the run no longer fails
  with the report's kind of failure, so it fails once the bug is fixed.

  The source is formatted with the default formatter options whenever it
  parses.

  ## Options

  - `:module_name` - Module name for the test (optional, auto-generated)
  - `:model` - Model module to use (falls back to FailureReport.model(report))
  - `:targets` - Validated single-entry target list the generated test runs
    against (falls back to the report's reference target; a report with a
    replay artifact replays it on all the report's targets)
  - `:test_name` - Custom test name (optional)
  - `:expect_fixed` - `true` for the regression guard, `false` for the
    reproduce form (default: `true`)
  """
  @spec generate(FailureReport.t(), keyword()) :: String.t()
  def generate(%FailureReport{} = report, opts \\ []) do
    metadata = Common.extract_metadata(report)
    model = Keyword.get(opts, :model, metadata.model)
    target = target_for(opts, metadata)
    given? = Keyword.has_key?(opts, :targets)
    expect_fixed = Keyword.get(opts, :expect_fixed, true)

    module_name = Keyword.get(opts, :module_name, generate_module_name(metadata))
    test_name = Keyword.get(opts, :test_name, generate_test_name(metadata, expect_fixed))
    adapter = if names_adapter?(report, given?), do: target.adapter || YourAdapter

    [
      generate_moduledoc(metadata),
      generate_module_header(module_name, model, adapter, expect_fixed),
      generate_test(report, test_name, {target, given?}, expect_fixed),
      generate_module_footer()
    ]
    |> Enum.join("\n")
    |> format_source()
  end

  # A target config that holds a value with no source literal (a pid, for
  # one) does not parse, and the formatter cannot format it; such source is
  # returned as generated.
  defp format_source(source) do
    case Code.string_to_quoted(source) do
      {:ok, _quoted} -> IO.iodata_to_binary([Code.format_string!(source), "\n"])
      {:error, _reason} -> source
    end
  end

  # ============================================================================
  # Module Structure
  # ============================================================================

  defp generate_moduledoc(metadata) do
    timestamp =
      case metadata.timestamp do
        %DateTime{} = dt -> DateTime.to_date(dt) |> Date.to_string()
        _ -> Date.utc_today() |> Date.to_string()
      end

    """
    # Regression test generated by PropertyDamage
    # Failure: #{failure_description(metadata)}
    # Date: #{timestamp}
    # Seed: #{metadata.seed}
    """
  end

  defp failure_description(metadata) do
    case metadata.check_name do
      nil -> to_string(metadata.kind)
      check -> "#{Common.check_label(check)} check failed"
    end
  end

  # The adapter alias is emitted only when the run options name `Adapter`: a
  # replay of the report's own targets names them in full.
  defp generate_module_header(module_name, model, adapter, expect_fixed) do
    model_str = if model, do: inspect(model), else: "YourModel"

    adapter_alias =
      if adapter, do: "\n  alias #{inspect(adapter)}, as: Adapter", else: ""

    """
    defmodule #{inspect(normalize_module_name(module_name))} do
      @moduledoc \"\"\"
    #{mode_doc(expect_fixed)}  \"\"\"
      use ExUnit.Case, async: true

      alias #{model_str}, as: Model#{adapter_alias}
    """
  end

  defp mode_doc(true) do
    """
      Regression guard for a failure PropertyDamage found.

      The test fails if the run finds any failure, so it fails while the bug
      is present and again if the bug comes back. It passes once the bug is
      fixed.
    """
  end

  defp mode_doc(false) do
    """
      Reproduction of a failure PropertyDamage found.

      The test fails if the run no longer fails with the recorded kind of
      failure, so it passes only while the bug is present. Once the bug is
      fixed, export the test again with `expect_fixed: true` to guard against
      its return.
    """
  end

  defp normalize_module_name(name) when is_binary(name), do: Module.concat([name])
  defp normalize_module_name(name), do: name

  defp generate_test(report, test_name, target, expect_fixed) do
    seed = FailureReport.seed(report)
    {run_comment, run_opts} = generate_run_opts(report, target)

    assertion =
      if expect_fixed do
        generate_expect_pass_assertion()
      else
        generate_expect_fail_assertion(report)
      end

    """
      @tag :regression
      @tag seed: #{seed}
      test "#{test_name}" do
    #{generate_commands_comment(report)}
        # #{run_comment}
        result = PropertyDamage.run(#{run_opts})

    #{assertion}
      end
    """
  end

  defp generate_module_footer do
    "end\n"
  end

  # ============================================================================
  # Commands Comment
  # ============================================================================

  # The shrunk sequence, for the reader: the test reproduces the failure by
  # replaying the report's artifact or by re-running its seed, so the commands
  # are listed as comments, not executed.
  defp generate_commands_comment(report) do
    roots =
      report
      |> FailureReport.steps()
      |> Enum.map_join("", fn step ->
        label =
          if is_binary(step.label), do: "    #   # #{step.label}\n", else: ""

        label <> "    #   #{format_command(step.command)}\n"
      end)

    """
    #{setup_comment(FailureReport.setup_commands(report))}    # Shrunk command sequence that triggers the failure:
    #{roots}
    """
  end

  defp setup_comment([]), do: ""

  defp setup_comment(setup_commands) do
    lines =
      Enum.map_join(setup_commands, "", fn command ->
        "    #   " <> format_command(command) <> "\n"
      end)

    "    # Setup commands, run before the roots:\n" <> lines
  end

  defp format_command(command) do
    module = command.__struct__
    fields = Map.from_struct(command)

    if map_size(fields) == 0 do
      "%#{inspect(module)}{}"
    else
      field_strs =
        fields
        |> Enum.map_join(", ", fn {k, v} -> "#{k}: #{format_field_value(v)}" end)

      "%#{inspect(module)}{#{field_strs}}"
    end
  end

  # A placeholder is opaque: its inspected form names the producer's field
  # and position.
  defp format_field_value(%PropertyDamage.Placeholder{} = placeholder), do: inspect(placeholder)

  # Note: is_atom also covers booleans and nil, which inspect correctly
  defp format_field_value(value) when is_atom(value), do: inspect(value)
  defp format_field_value(value) when is_binary(value), do: inspect(value)
  defp format_field_value(value) when is_number(value), do: inspect(value)

  defp format_field_value(value) when is_list(value) do
    items = Enum.map_join(value, ", ", &format_field_value/1)
    "[#{items}]"
  end

  defp format_field_value(value) when is_map(value) do
    if struct_value?(value) do
      format_command(value)
    else
      items =
        Enum.map_join(value, ", ", fn {k, v} ->
          "#{format_map_key(k)} => #{format_field_value(v)}"
        end)

      "%{#{items}}"
    end
  end

  # PIDs/references/functions/ports have no valid source literal; inspect/1
  # renders them as `#PID<...>` etc., which is a syntax error in generated code.
  defp format_field_value(value)
       when is_pid(value) or is_reference(value) or is_function(value) or is_port(value),
       do: "nil"

  defp format_field_value(value) do
    inspected = inspect(value)
    # Any other `#...`-prefixed inspect output (e.g. a struct with a custom
    # Inspect impl) is not a valid literal either; fall back to something that
    # compiles rather than emitting un-parseable code.
    if String.starts_with?(inspected, "#"), do: "nil", else: inspected
  end

  defp format_map_key(key) when is_atom(key), do: inspect(key)
  defp format_map_key(key), do: inspect(key)

  defp struct_value?(%{__struct__: _}), do: true
  defp struct_value?(_), do: false

  # ============================================================================
  # Run Options
  # ============================================================================

  # A report with a replay artifact replays it, on the report's targets (or
  # the `:targets` given), so the test names the file it reads, which records
  # the run's atom markers; any other report re-runs its seed on one target,
  # with the `max_commands:` and the markers the report records, since both
  # decide the sequence the seed generates.
  defp generate_run_opts(%FailureReport{replay_path: path} = report, {target, given?})
       when is_binary(path) do
    targets =
      if given?,
        do: "[#{target_entry_source(target)}]",
        else: FailureReport.targets_source(report)

    {"Replay the artifact the failing run wrote",
     Enum.join(
       ["model: Model", "targets: #{targets}", "only: [replay: #{inspect(path)}]"],
       ",\n          "
     )}
  end

  defp generate_run_opts(report, {target, _given?}) do
    opts = [
      "model: Model",
      "targets: [#{target_entry_source(target)}]",
      "seed: #{FailureReport.seed(report)}",
      "max_runs: 1",
      report.max_commands && "max_commands: #{report.max_commands}",
      FailureReport.external_markers(report) != [] &&
        "external_markers: #{inspect(FailureReport.external_markers(report))}"
    ]

    opts = Enum.filter(opts, &is_binary/1)

    {"Run with the exact seed for deterministic reproduction", Enum.join(opts, ",\n          ")}
  end

  # The target entry as source: the aliased module alone, or a tuple carrying
  # only the keys that differ from the entry defaults.
  defp target_entry_source(target) do
    extras =
      [
        if(target.name != PropertyDamage.Target.default_name(target.adapter),
          do: "name: #{inspect(target.name)}"
        ),
        if(target.config != %{}, do: "config: #{inspect(target.config)}"),
        if(target.injectors != [], do: "injectors: #{inspect(target.injectors)}"),
        if(target.mocks != [], do: "mocks: #{inspect(target.mocks)}")
      ]
      |> Enum.reject(&is_nil/1)

    case extras do
      [] -> "Adapter"
      extras -> "{Adapter, #{Enum.join(extras, ", ")}}"
    end
  end

  # Whether the run options name the `Adapter` alias: every form except the
  # replay of the report's own targets.
  defp names_adapter?(%FailureReport{replay_path: path}, given?) when is_binary(path), do: given?
  defp names_adapter?(_report, _given?), do: true

  defp target_for(opts, metadata) do
    case Keyword.get(opts, :targets) do
      nil ->
        metadata.target || %PropertyDamage.Target{index: 0}

      entries ->
        PropertyDamage.Options.single_target!(entries)
    end
  end

  # ============================================================================
  # Assertions
  # ============================================================================

  defp generate_expect_pass_assertion do
    """
        # Expect the bug to be fixed (test passes)
        case result do
          {:ok, _stats} ->
            :ok

          {:error, failure} ->
            flunk(\"\"\"
            Bug has resurfaced!

            Expected the bug to be fixed, but PropertyDamage found a failure:
            \#{PropertyDamage.FailureReport.failure_message(failure)}

            Seed: \#{PropertyDamage.FailureReport.seed(failure)}
            \"\"\")
        end
    """
  end

  defp generate_expect_fail_assertion(report) do
    kind = FailureReport.kind(report)

    check_match =
      case FailureReport.check_name(report) do
        nil ->
          ""

        check ->
          "\n          assert PropertyDamage.FailureReport.check_name(failure) == #{inspect(check)}"
      end

    """
        # Expect the failure to still reproduce
        case result do
          {:ok, _stats} ->
            flunk(\"\"\"
            The failure no longer reproduces.

            This test asserts that the recorded failure still happens. If the
            bug is fixed, export the test again with expect_fixed: true to
            guard against its return.
            \"\"\")

          {:error, failure} ->
            # Confirm we get the same type of failure
            assert PropertyDamage.FailureReport.kind(failure) == #{inspect(kind)}#{check_match}
        end
    """
  end

  # ============================================================================
  # Name Generation
  # ============================================================================

  defp generate_module_name(metadata) do
    Module.concat([Regressions, :"Seed#{metadata.seed}Test"])
  end

  defp generate_test_name(metadata, true) do
    case metadata.check_name do
      nil -> "#{metadata.kind} failure stays fixed (seed #{metadata.seed})"
      check -> "#{Common.check_label(check)} violation stays fixed (seed #{metadata.seed})"
    end
  end

  defp generate_test_name(metadata, false) do
    case metadata.check_name do
      nil -> "reproduces #{metadata.kind} failure (seed #{metadata.seed})"
      check -> "reproduces #{Common.check_label(check)} violation (seed #{metadata.seed})"
    end
  end
end
