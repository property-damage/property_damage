defmodule PropertyDamage.Sequence do
  @moduledoc """
  Represents a command sequence: the roots that run one after another.

  The roots are held in `prefix`:

      %Sequence{prefix: [cmd1, cmd2, cmd3]}

  Use `Sequence.linear/1` as a convenience constructor:

      Sequence.linear([cmd1, cmd2, cmd3])

  ## Setup and teardown commands

  `setup` holds the model's setup commands (`c:PropertyDamage.Model.setup_each/0`)
  and `teardown` its teardown commands (`c:PropertyDamage.Model.teardown_each/0`),
  as generated for this sequence. They run before and after the roots and are not
  roots themselves: every function here that reads commands (`to_list/1`,
  `command_count/1`, `indexed/1`, `position_at/2`, `map/2`, `filter/2`, ...)
  reads the roots only and carries the two lists through unchanged. Read them
  with `setup_commands/1` and `teardown_commands/1`.

  ## Placeholders

  A value the system mints is a placeholder (see `PropertyDamage.External`).
  A command can use a placeholder only after the command that mints it.
  """

  alias PropertyDamage.Sequence.Position

  @type command :: struct()

  @type t :: %__MODULE__{
          prefix: [command()],
          setup: [command()],
          teardown: [command()],
          # Internal placeholder registry (DR-021); opaque to users.
          registry: term() | nil
        }

  defstruct prefix: [], setup: [], teardown: [], registry: nil

  @doc "The setup commands that run before the roots, in order."
  @spec setup_commands(t()) :: [command()]
  def setup_commands(%__MODULE__{setup: setup}), do: setup

  @doc "The teardown commands that run after the roots, in order."
  @spec teardown_commands(t()) :: [command()]
  def teardown_commands(%__MODULE__{teardown: teardown}), do: teardown

  @doc """
  Create a sequence whose roots are `commands`, in order.

  ## Examples

      iex> seq = PropertyDamage.Sequence.linear([cmd1, cmd2, cmd3])
      iex> seq.prefix
      [cmd1, cmd2, cmd3]
  """
  @spec linear([command()]) :: t()
  def linear(commands) when is_list(commands) do
    %__MODULE__{prefix: commands}
  end

  @doc false
  # Attach a placeholder registry to a sequence (DR-021). Internal plumbing:
  # sequence generation uses this to carry the id-indexed registry + producer
  # link from generation to execution. `to_list/1` deliberately drops it.
  @spec with_registry(t(), term() | nil) :: t()
  def with_registry(%__MODULE__{} = seq, registry) do
    %{seq | registry: registry}
  end

  @doc """
  Compute a stable fingerprint of a plan (DR-036).

  The fingerprint is a hex-encoded SHA-256 digest of the canonical plan: the
  roots and the setup and teardown commands (left out when both are empty, so a plan
  without them keeps its earlier fingerprint), with all
  symbolic markers carrying their deterministic ids (DR-036), and with the
  derived `registry` field excluded (it is rebuilt per run and is not part of
  the plan's meaning).

  Two plans are "the same plan" for run comparison (DR-035) iff their
  fingerprints are equal. Because placeholder ids are deterministic functions
  of generation coordinates, two independent generations of the same plan
  (same effective seed, same generator code) fingerprint identically; a plan
  generated by different generator code (changed command/event structs)
  fingerprints differently, which is the correct signal for the cross-commit
  regression use case.

  Encoding uses `:erlang.term_to_binary/2` with `minor_version: 2`, stable for
  the term types involved across supported OTP releases.
  """
  @spec fingerprint(t()) :: String.t()
  def fingerprint(%__MODULE__{} = sequence) do
    # The canonical term keeps the shape earlier plans hashed, whose second and
    # third elements are now always `nil` and `[]`, so a plan keeps its
    # fingerprint. A plan without setup and teardown commands keeps the
    # fingerprint it had before they existed, so earlier traces still compare.
    canonical =
      case {sequence.setup, sequence.teardown} do
        {[], []} -> {sequence.prefix, nil, []}
        {setup, teardown} -> {sequence.prefix, nil, [], setup, teardown}
      end

    :crypto.hash(:sha256, :erlang.term_to_binary(canonical, minor_version: 2))
    |> Base.encode16(case: :lower)
  end

  @doc """
  The number of roots in the sequence.

  ## Examples

      iex> seq = PropertyDamage.Sequence.linear([cmd1, cmd2])
      iex> PropertyDamage.Sequence.command_count(seq)
      2
  """
  @spec command_count(t()) :: non_neg_integer()
  def command_count(%__MODULE__{prefix: prefix}), do: length(prefix)

  @doc """
  The roots of the sequence, in order.

  ## Examples

      iex> seq = PropertyDamage.Sequence.linear([cmd1, cmd2])
      iex> PropertyDamage.Sequence.to_list(seq)
      [cmd1, cmd2]
  """
  @spec to_list(t()) :: [command()]
  def to_list(%__MODULE__{prefix: prefix}), do: prefix

  @doc """
  Pair every root with its structured `Position` and its index.

  Returns `[{%Position{}, index, command}]` in `to_list/1` order. The `index`
  is the `0..n-1` ordinal in that order (the same index `command_labels`,
  exporters and diff key on); the `Position` is the command's canonical
  section and offset.

  ## Examples

      iex> seq = PropertyDamage.Sequence.linear([:a, :b])
      iex> PropertyDamage.Sequence.indexed(seq)
      [
        {%PropertyDamage.Sequence.Position{section: :prefix, offset: 0}, 0, :a},
        {%PropertyDamage.Sequence.Position{section: :prefix, offset: 1}, 1, :b}
      ]
  """
  @spec indexed(t()) :: [{Position.t(), non_neg_integer(), command()}]
  def indexed(%__MODULE__{prefix: prefix}) do
    prefix
    |> Enum.with_index()
    |> Enum.map(fn {command, index} -> {Position.prefix(index), index, command} end)
  end

  @doc """
  Resolve an executor command index to its `Position`.

  The result is consistent with `indexed/1`: the position returned for an
  event log entry's `command_index` is exactly the position of the command
  that produced it.

  ## Examples

      iex> seq = PropertyDamage.Sequence.linear([:a, :b])
      iex> PropertyDamage.Sequence.position_at(seq, 1)
      %PropertyDamage.Sequence.Position{section: :prefix, offset: 1}
  """
  @spec position_at(t(), non_neg_integer()) :: Position.t()
  def position_at(%__MODULE__{}, command_index), do: Position.prefix(command_index)

  @doc """
  Map a function over all roots in the sequence.

  ## Examples

      iex> seq = PropertyDamage.Sequence.linear([1, 2, 3])
      iex> PropertyDamage.Sequence.map(seq, &(&1 * 2)).prefix
      [2, 4, 6]
  """
  @spec map(t(), (command() -> command())) :: t()
  def map(%__MODULE__{prefix: prefix} = seq, fun), do: %{seq | prefix: Enum.map(prefix, fun)}

  @doc """
  Keep the roots for which `pred` returns a truthy value.
  """
  @spec filter(t(), (command() -> boolean())) :: t()
  def filter(%__MODULE__{prefix: prefix} = seq, pred),
    do: %{seq | prefix: Enum.filter(prefix, pred)}

  @doc """
  Append a command to the end of the sequence.
  """
  @spec append(t(), command()) :: t()
  def append(%__MODULE__{} = seq, command), do: %{seq | prefix: seq.prefix ++ [command]}

  @doc """
  Prepend a command to the beginning of the sequence.
  """
  @spec prepend(t(), command()) :: t()
  def prepend(%__MODULE__{} = seq, command) do
    %{seq | prefix: [command | seq.prefix]}
  end
end
